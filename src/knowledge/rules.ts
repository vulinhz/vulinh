/**
 * Hàm tìm kiếm quy tắc phù hợp với lá số
 */
export function findMatchingRules(
  topic?: string,
  stars: string[] = [],
  palaceName?: string
): TuViRule[] {
  return TUVI_RULES.filter(rule => {
    if (topic && rule.topic !== topic) return false;
    if (palaceName && rule.palaces_involved && rule.palaces_involved.length > 0) {
      if (!rule.palaces_involved.includes(palaceName)) return false;
    }
    if (stars.length > 0 && rule.stars_involved.length > 0) {
      const hasCommonStar = rule.stars_involved.some(s => stars.includes(s));
      if (!hasCommonStar) return false;
    }
    return true;
  });
}
